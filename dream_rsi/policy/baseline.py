"""Fixed baseline exploration policy (read-only reference for agents).

Agents may **read** this module to understand a working strategy, then implement
something better in ``dream_rsi/policy/discovered/method.py`` using the public API only.
Do not edit this file during heuristic search.
"""

from __future__ import annotations

from typing import Any, Dict, Optional

from dream_rsi.env.types import SearchEnv
from dream_rsi.policy.api import LLMDesignedMethod, SimResult, _budget_done, _record_curve, finalize_result


def _take_cells(cells: list[str], question: SearchEnv, budget: int | None) -> list[str]:
    """Cap a wave to remaining budget (same semantics as runner ``take()``)."""
    if budget is None:
        return cells
    remaining = budget - question.budget_spent
    if remaining <= 0:
        return []
    return cells[:remaining]


def _probe_wave(question: SearchEnv, cells: list[str], res: SimResult) -> None:
    if hasattr(question, "probe_batch"):
        question.probe_batch(cells, on_reveal=lambda _: _record_curve(res, question))
    else:
        for cell_id in cells:
            question.probe(cell_id)
            _record_curve(res, question)


def _wave_cells(
    question: SearchEnv,
    attempt: int,
    *,
    max_width: int | None,
    max_refine: int,
) -> list[str]:
    """Legal cells at one dependency wave (same attempt depth), within width/refine caps."""
    if attempt > max_refine:
        return []
    return sorted(
        (
            a
            for a in question.legal_actions()
            if question.meta(a).attempt == attempt
            and (max_width is None or question.meta(a).branch < max_width)
        ),
        key=lambda a: (question.meta(a).branch, question.meta(a).seq),
    )


class ParallelRefineMethod(LLMDesignedMethod):
    """Wave-parallel explore + refine (offline replay of the online explore runner).

    Hyperparameters (``config`` dict):

    - ``max_width`` / ``width``: max branch index to explore (M in
      ``DRSI_PARALLEL_EXPLORE``). ``None`` = all branches present in the trace.
    - ``max_refine`` / ``max_depth``: deepest attempt index to probe (N refines
      after root → attempts ``0..max_refine``; default 2 like online runner).

    Waves:

    - wave attempt=0: parallel open roots ``b0_a0 … b{M-1}_a0``
    - wave attempt=1: parallel refine depth 1 on each branch
    - … until ``max_refine``
    """

    NAME = "parallel_refine"

    def __init__(self, config: Optional[Dict[str, Any]] = None):
        super().__init__(config)
        width = self.config.get("max_width", self.config.get("width"))
        self.max_width: int | None = int(width) if width is not None else None
        self.max_refine = int(self.config.get("max_refine", self.config.get("max_depth", 10)))

    def solve(self, question: SearchEnv, budget: int | None = None) -> SimResult:
        question.reset()
        res = SimResult()

        for attempt in range(self.max_refine + 1):
            if _budget_done(question, budget):
                return finalize_result(question, res)
            cells = _take_cells(
                _wave_cells(
                    question,
                    attempt,
                    max_width=self.max_width,
                    max_refine=self.max_refine,
                ),
                question,
                budget,
            )
            if not cells:
                continue
            _probe_wave(question, cells, res)

        return finalize_result(question, res)
